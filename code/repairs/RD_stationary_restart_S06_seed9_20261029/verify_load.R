args <- commandArgs(TRUE)
stopifnot(length(args)==1L)
root <- normalizePath(args[1],winslash='/',mustWork=TRUE)
if(.Platform$OS.type=='windows') Sys.setlocale('LC_CTYPE','English_United States.utf8')
code <- file.path(root,'code')
files <- list.files(code,pattern='\\.R$',recursive=TRUE,full.names=TRUE)
invisible(lapply(files,function(f) parse(f,encoding='UTF-8')))
source(file.path(code,'RD/load_anchored_rd.R'),encoding='UTF-8')
source_anchored_rd(code,file.path(code,'RD'))
stopifnot(exists('exact_marginal_rd_target'),is.function(exact_marginal_rd_target))
cat('PASS:',length(files),'R source files parsed; repair runtime loaded without fitting or interval inversion.\n')
